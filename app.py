def finite_numeric(series: pd.Series) -> pd.Series:
    return pd.to_numeric(series, errors="coerce").replace(
        [np.inf, -np.inf], np.nan
    )


def get_qsm_inventory(df: pd.DataFrame) -> pd.DataFrame:
    required = ["DBH_cm", "H_m", "Volume_total_m3"]
    if not all(c in df.columns for c in required):
        return pd.DataFrame()

    out = df.copy()
    for c in required:
        out[c] = finite_numeric(out[c])

    return out[
        out["DBH_cm"].notna()
        & out["H_m"].notna()
        & out["Volume_total_m3"].notna()
    ].copy()


def fmt(value, digits=1, suffix=""):
    try:
        if pd.isna(value):
            return "NA"
        return f"{float(value):,.{digits}f}{suffix}"
    except Exception:
        return "NA"


# ============================================================
# INLINE LOCAL HTMLWIDGET ASSETS
#
# QSM viewer pages were generated by R htmlwidgets with
# selfcontained = FALSE. On Streamlit Community Cloud we read
# the selected HTML file and inline its local JS/CSS assets
# before passing it to components.html().
# ============================================================

def _is_remote(url: str) -> bool:
    u = url.lower().strip()
    return (
        u.startswith("http://")
        or u.startswith("https://")
        or u.startswith("//")
        or u.startswith("data:")
        or u.startswith("blob:")
        or u.startswith("#")
    )


def _inline_css_urls(css_text: str, css_dir: Path) -> str:
    pattern = re.compile(r"url\((['\"]?)([^)'\"\s]+)\1\)")

    def repl(match):
        raw = match.group(2).strip()
        if _is_remote(raw):
            return match.group(0)

        asset = (css_dir / raw).resolve()
        if not asset.exists() or not asset.is_file():
            return match.group(0)

        mime = mimetypes.guess_type(asset.name)[0] or "application/octet-stream"
        encoded = base64.b64encode(asset.read_bytes()).decode("ascii")
        return f"url(data:{mime};base64,{encoded})"

    return pattern.sub(repl, css_text)


@st.cache_data(show_spinner=False)
def inline_html_file(path_string: str, mtime_ns: int) -> str:
    """
    Read a generated QSM HTML viewer and inline all local JS/CSS.
    mtime_ns is included only to invalidate the Streamlit cache if
    the viewer file changes.
    """
    path = Path(path_string)
    html = path.read_text(encoding="utf-8", errors="replace")
    soup = BeautifulSoup(html, "html.parser")

    # Inline local stylesheets.
    for link in list(soup.find_all("link", href=True)):
        rel = [str(x).lower() for x in (link.get("rel") or [])]
        if "stylesheet" not in rel:
            continue

        href = link.get("href", "")
        if not href or _is_remote(href):
            continue

        css_path = (path.parent / href).resolve()
        if not css_path.exists():
            continue

        css = css_path.read_text(encoding="utf-8", errors="replace")
        css = _inline_css_urls(css, css_path.parent)

        style = soup.new_tag("style")
        style.string = css
        link.replace_with(style)

    # Inline local JavaScript.
    for script in list(soup.find_all("script", src=True)):
        src = script.get("src", "")
        if not src or _is_remote(src):
            continue

        js_path = (path.parent / src).resolve()
        if not js_path.exists():
            continue

        js = js_path.read_text(encoding="utf-8", errors="replace")
        new_script = soup.new_tag("script")
        new_script.string = js
        script.replace_with(new_script)

    # Remove base tags if present, because the widget is injected into
    # a Streamlit component iframe rather than opened from disk.
    for base_tag in soup.find_all("base"):
        base_tag.decompose()

    return str(soup)


def resolve_viewer_path(viewer_value: str) -> Optional[Path]:
    if not isinstance(viewer_value, str) or not viewer_value.strip():
        return None

    value = viewer_value.replace("\\", "/").strip()

    # Manifest usually contains QSM_viewers/tree_XXXXX.html.
    candidates = [
        DATA / value,
        DATA / "QSM_viewers" / Path(value).name,
    ]

    for candidate in candidates:
        if candidate.exists():
            return candidate.resolve()

    return None


