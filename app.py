with tab_reclass:
    st.subheader("QSF-assisted semantic reclassification")

    st.write(
        "This section keeps the quantitative before/after summary. "
        "The heavy forest-wide 3D comparison is intentionally omitted "
        "because the point cloud is now inspected directly against each "
        "selected QSM in the Tree explorer."
    )

    def semantic_counts(df: pd.DataFrame, stage: str) -> pd.DataFrame:
        if df.empty or "semantic_label" not in df.columns:
            return pd.DataFrame()
        out = (
            df["semantic_label"]
            .astype(str)
            .value_counts()
            .rename_axis("semantic_label")
            .reset_index(name="N")
        )
        out["Stage"] = stage
        return out

    counts = pd.concat(
        [
            semantic_counts(semantic_before, "Before"),
            semantic_counts(semantic_after, "After"),
        ],
        ignore_index=True,
    )

    if not counts.empty:
        fig = px.bar(
            counts,
            x="semantic_label",
            y="N",
            color="Stage",
            barmode="group",
            title="Sampled point counts by semantic class",
        )
        st.plotly_chart(fig, width="stretch")

    if (
        not semantic_transition.empty
        and {
            "semantic_before",
            "semantic_after",
            "N",
        }.issubset(semantic_transition.columns)
    ):
        trans = semantic_transition.copy()
        trans["N"] = finite_numeric(trans["N"]).fillna(0)

        before_names = [
            f"Before: {x}"
            for x in trans["semantic_before"].astype(str)
        ]
        after_names = [
            f"After: {x}"
            for x in trans["semantic_after"].astype(str)
        ]
        labels = list(dict.fromkeys(before_names + after_names))
        label_index = {name: i for i, name in enumerate(labels)}

        source = [
            label_index[f"Before: {x}"]
            for x in trans["semantic_before"].astype(str)
        ]
        target = [
            label_index[f"After: {x}"]
            for x in trans["semantic_after"].astype(str)
        ]

        fig = go.Figure(
            go.Sankey(
                node=dict(label=labels, pad=15, thickness=18),
                link=dict(
                    source=source,
                    target=target,
                    value=trans["N"].tolist(),
                ),
            )
        )
        fig.update_layout(
            title="Point-class transitions produced by QSF reclassification",
            height=600,
        )
        st.plotly_chart(fig, width="stretch")
    else:
        st.info("Semantic transition table is not available.")


